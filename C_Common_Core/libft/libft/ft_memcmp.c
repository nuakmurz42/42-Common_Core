#include "libft.h"

int	ft_memcmp(const void *s1, const void *s2, size_t n)
{
	size_t				i;
	const unsigned char	*s01 = (const unsigned char *)s1;
	const unsigned char	*s02 = (const unsigned char *)s2;

	i = 0;
	if (n == 0)
		return (0);
	while (i < n)
	{
		if (s01[i] != s02[i])
			return (s01[i] - s02[i]);
		i++;
	}
	return (0);
}
