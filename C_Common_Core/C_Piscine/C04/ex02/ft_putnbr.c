#include <unistd.h>

void	ft_putnbr(int nb)
{
	char	c;
	int		sign;

	sign = -1;
	if (nb == -2147483648)
	{
		ft_putnbr(nb / 10);
		write(1, "8", 1);
		return ;
	}
	if (nb < 0)
	{
		write(1, "-", 1);
		nb *= sign;
	}
	if (nb > 9)
		ft_putnbr(nb / 10);
	c = '0' + (nb % 10);
	write (1, &c, 1);
}
