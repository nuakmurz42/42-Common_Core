#include <unistd.h>

void	ft_putstr(char *str)
{
	int	i;

	i = 0;
	while (str[i] && (str[i] >= 0 && str[i] < 32))
		i++;
	while (str[i])
	{
		write(1, &str[i], 1);
		i++;
	}
}
